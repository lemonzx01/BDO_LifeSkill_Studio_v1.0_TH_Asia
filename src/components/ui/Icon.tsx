/**
 * `<Icon name="search" />`: 20px by default (buttons, nav); size it with classes at the call site
 * ("h-4 w-4" inline in text and pills, "h-6 w-6" at most for decoration). The colour is the text
 * colour (currentColor).
 *
 * Decorative by default (aria-hidden): put the words on the button or link, or an aria-label on an
 * icon-only button. Pass `label` (or `title`) only when the icon itself carries meaning that is
 * written nowhere else; it then becomes an image with that name and a hover title.
 */
export function Icon({
  name,
  className = "",
  label,
  title,
  strokeWidth = 1.75,
}: {
  name: IconName;
  /** size and colour, e.g. "h-4 w-4 text-good" */
  className?: string;
  /** the accessible name, for an icon that means something on its own; leave out when decorative */
  label?: string;
  /** the same as `label` (a hover title that is also the accessible name) */
  title?: string;
  strokeWidth?: number;
}) {
  const named = label ?? title;
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      // the default size; classes such as h-4 w-4 override it
      width={20}
      height={20}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`shrink-0 ${className}`}
      role={named ? "img" : undefined}
      aria-label={named}
      aria-hidden={named ? undefined : true}
      focusable="false"
    >
      {named && <title>{named}</title>}
      {ICONS[name]}
    </svg>
  );
}
